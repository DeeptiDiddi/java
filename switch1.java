public class switch1{
 public static void main(String[] arg){
  int a=3;
  switch(a)
  {
   case 1:
    System.out.println("One");
    break;
   case 2:
    System.out.println("Two");
    break;
   case 3:
    System.out.println("Three");
    break;
   default:
    System.out.println("Other");
  }
 }
}
